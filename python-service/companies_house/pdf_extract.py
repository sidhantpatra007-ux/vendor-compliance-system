"""
companies_house/pdf_extract.py

Extracts financial concepts from Companies House accounts filings that
are ONLY available as PDF (no iXBRL/XHTML version) — the case xbrl.py
currently gives up on and scores as NO_STRUCTURED_FINANCIAL_DATA.

Scope and assumptions:
  - This targets Companies House's own PDF filings specifically, which
    are near-universally digitally generated by accounting/filing
    software (not scanned photos) — so a real text layer is expected.
    Scanned filings fall through to ocr_extract.py instead.
  - This module ONLY extracts candidate values. It does not decide
    whether they're trustworthy, does not gate them behind approval,
    and does not merge them into any "final" signals dict. Every value
    returned here is unconfirmed until a human reviews it — hence
    `needs_manual_review` is always True on any matched concept, and
    each matched concept carries an evidence image of its source page
    for that review (see evidence.py).
  - PDF text extraction has no semantic tagging like XBRL concept
    labels — matching is done by finding a keyword phrase on a line
    and looking at the numbers that follow it. UK balance sheets
    conventionally show current-year first, prior-year second in an
    adjacent column — but multi-year comparison tables (common in
    larger/international filings) put several years' figures on one
    line, so a line with MORE THAN ONE number is flagged as
    AMBIGUOUS_MULTIPLE_VALUES rather than silently guessing which one
    is current-year.
  - Currency/locale: numbers are parsed via amount_parse.py, which
    handles £/€/$ symbols and both UK/US ("1,234.56") and EU
    ("1.234,56") separator conventions.
  - File lifecycle: this module does NOT download or delete the PDF —
    the caller (evaluate.py) owns the downloaded file's path and
    lifecycle, since the OCR fallback tier may need the same file
    afterward. Use download_accounts_pdf() to get that path.

Requires: pdfplumber, httpx
"""

